#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Enrich UE 304 data files and Excel database with correction source metadata:
- official: from official correction documents
- syllabus: from the course PDF (PY00304T SI-26-27-IRIS.pdf)
- ai: generated by AI
"""

import json
import os
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(BASE_DIR, "..", "data")
DOCS_DIR = os.path.join(BASE_DIR, "..", "docs")

QCM_JSON = os.path.join(DATA_DIR, "questions_database.json")
OPEN_JSON = os.path.join(DATA_DIR, "open_questions.json")
AI_JSON = os.path.join(DATA_DIR, "embedded_ai_bank.json")
EXCEL_PATH = os.path.join(DOCS_DIR, "UE304_questions_database.xlsx")

def main():
    # 1. Update QCM JSON
    with open(QCM_JSON, "r", encoding="utf-8") as f:
        qcm_data = json.load(f)

    for q in qcm_data:
        doc = q.get("document", "")
        if "2018-2019" in doc:
            q["correction_source_type"] = "official"
            q["correction_source"] = "Corrigé officiel"
            q["correction_source_detail"] = "304_Annale_-_2018-2019_Session_1_CORRECTION.pdf (Document officiel certifié)"
        else:
            q["correction_source_type"] = "syllabus"
            q["correction_source"] = "PDF du cours"
            q["correction_source_detail"] = "PY00304T SI-26-27-IRIS.pdf (Polycopié officiel de cours)"

    with open(QCM_JSON, "w", encoding="utf-8") as f:
        json.dump(qcm_data, f, ensure_ascii=False, indent=2)
    print(f"✅ Updated {len(qcm_data)} QCM in {QCM_JSON}")

    # 2. Update Open Questions JSON
    with open(OPEN_JSON, "r", encoding="utf-8") as f:
        open_data = json.load(f)

    for q in open_data:
        qid = q.get("id", "")
        if qid in ("OPEN-4", "OPEN-5"):
            q["correction_source_type"] = "official"
            q["correction_source"] = "Corrigé officiel"
            q["correction_source_detail"] = "304_Annale_-2021-2022_correction_questions_ouvertes.pdf (Document officiel)"
        else:
            q["correction_source_type"] = "syllabus"
            q["correction_source"] = "PDF du cours"
            q["correction_source_detail"] = "PY00304T SI-26-27-IRIS.pdf (Polycopié officiel de cours)"

    with open(OPEN_JSON, "w", encoding="utf-8") as f:
        json.dump(open_data, f, ensure_ascii=False, indent=2)
    print(f"✅ Updated {len(open_data)} open questions in {OPEN_JSON}")

    # 3. Update AI Bank JSON
    with open(AI_JSON, "r", encoding="utf-8") as f:
        ai_data = json.load(f)

    for q in ai_data:
        q["correction_source_type"] = "ai"
        q["correction_source"] = "Généré par IA"
        q["correction_source_detail"] = "Banque de questions d'entraînement générées par IA (Gemini / Claude)"

    with open(AI_JSON, "w", encoding="utf-8") as f:
        json.dump(ai_data, f, ensure_ascii=False, indent=2)
    print(f"✅ Updated {len(ai_data)} AI bank questions in {AI_JSON}")

    # 4. Update Excel workbook
    if os.path.exists(EXCEL_PATH):
        wb = openpyxl.load_workbook(EXCEL_PATH)
        header_font = Font(name="Arial", size=10, bold=True, color="FFFFFF")
        header_fill = PatternFill(start_color="1F3864", end_color="1F3864", fill_type="solid")
        header_align = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell_font = Font(name="Arial", size=9)
        cell_align_left = Alignment(horizontal="left", vertical="top", wrap_text=True)
        thin_border = Border(
            left=Side(style="thin", color="D9D9D9"),
            right=Side(style="thin", color="D9D9D9"),
            top=Side(style="thin", color="D9D9D9"),
            bottom=Side(style="thin", color="D9D9D9")
        )

        # QCM Sheet
        if "QCM" in wb.sheetnames:
            ws_qcm = wb["QCM"]
            # Check if column 12 is already Correction Source
            col_12_val = ws_qcm.cell(1, 12).value
            ws_qcm.cell(1, 12, "Correction Source")
            ws_qcm.cell(1, 12).font = header_font
            ws_qcm.cell(1, 12).fill = header_fill
            ws_qcm.cell(1, 12).alignment = header_align
            ws_qcm.column_dimensions["L"].width = 35

            for r in range(2, ws_qcm.max_row + 1):
                doc = str(ws_qcm.cell(r, 1).value or "")
                if "2018-2019" in doc:
                    val = "Corrigé officiel : 304_Annale_-_2018-2019_Session_1_CORRECTION.pdf (Document officiel certifié)"
                else:
                    val = "PDF du cours : PY00304T SI-26-27-IRIS.pdf (Polycopié officiel de cours)"
                c = ws_qcm.cell(r, 12, val)
                c.font = cell_font
                c.border = thin_border
                c.alignment = cell_align_left

        # Open questions Sheet
        if "Open questions" in wb.sheetnames:
            ws_open = wb["Open questions"]
            ws_open.cell(1, 10, "Correction Source")
            ws_open.cell(1, 10).font = header_font
            ws_open.cell(1, 10).fill = header_fill
            ws_open.cell(1, 10).alignment = header_align
            ws_open.column_dimensions["J"].width = 35

            for r in range(2, ws_open.max_row + 1):
                doc = str(ws_open.cell(r, 1).value or "")
                q_num = str(ws_open.cell(r, 3).value or "")
                # Questions 4 & 5 (from 2021-2022) are the ones with official correction
                if "2021-2022" in doc:
                    val = "Corrigé officiel : 304_Annale_-2021-2022_correction_questions_ouvertes.pdf (Document officiel)"
                else:
                    val = "PDF du cours : PY00304T SI-26-27-IRIS.pdf (Polycopié officiel de cours)"
                c = ws_open.cell(r, 10, val)
                c.font = cell_font
                c.border = thin_border
                c.alignment = cell_align_left

        # Notes Sheet
        if "Notes" in wb.sheetnames:
            ws_notes = wb["Notes"]
            # Add Correction Source note
            ws_notes.append([
                "Correction Source",
                "Chaque question précise l'origine exacte de sa clé de correction selon 3 catégories : (1) 'Corrigé officiel' pour les épreuves disposant d'une grille ou d'un fascicule officiel de correction (2018-2019 S1 QCM, 2021-2022 Questions ouvertes) ; (2) 'PDF du cours' pour les réponses établies et vérifiées d'après le polycopié officiel PY00304T SI-26-27-IRIS.pdf (2024-2025 S1, 2023-2024 S1 & S2, 2022-2023 S1, 2021-2022 S1 QCM, 2020-2021 S1) ; (3) 'Généré par IA' pour la banque de questions d'entraînement générée par modèles d'intelligence artificielle."
            ])
            curr_r = ws_notes.max_row
            ws_notes.cell(curr_r, 1).font = Font(name="Arial", size=9, bold=True)
            ws_notes.cell(curr_r, 1).alignment = cell_align_left
            ws_notes.cell(curr_r, 1).border = thin_border
            ws_notes.cell(curr_r, 2).font = cell_font
            ws_notes.cell(curr_r, 2).alignment = cell_align_left
            ws_notes.cell(curr_r, 2).border = thin_border

        wb.save(EXCEL_PATH)
        print(f"✅ Updated Excel database at {EXCEL_PATH}")

if __name__ == "__main__":
    main()

